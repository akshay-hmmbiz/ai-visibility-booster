/**
 * AI Markdown Export
 *
 * Generates a dynamic Markdown representation of any post at:
 *   /ai-markdown/{post-slug}
 *
 * Content-Type: text/markdown
 * No physical files are created. Content is generated on demand.
 * Scripts, styles, and unsafe HTML are stripped before conversion.
 *
 * Plugin developed by Akshay Bhimani.
 *
 * @package AI_Visibility_Booster
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Output the Markdown representation of a post.
 *
 * @param string $slug The post slug to export.
 */
function aivb_output_markdown( $slug ) {
	if ( empty( $slug ) ) {
		status_header( 400 );
		exit;
	}

	$post = get_page_by_path( $slug, OBJECT, array( 'post', 'page' ) );

	// Password-protected posts are never exported: their content is not public.
	if ( ! $post || 'publish' !== $post->post_status || '' !== (string) $post->post_password ) {
		status_header( 404 );
		exit;
	}

	$post_id   = $post->ID;
	$summary   = aivb_get_summary( $post_id );
	$permalink = get_permalink( $post_id );
	$pub_date  = get_the_date( 'Y-m-d', $post_id );

	// Category names.
	$cats     = get_the_category( $post_id );
	$cat_list = '';
	if ( is_array( $cats ) && ! empty( $cats ) ) {
		$cat_list = implode( ', ', wp_list_pluck( $cats, 'name' ) );
	}

	// Run content through WordPress filters (shortcodes etc.), then sanitize.
	$raw_content = apply_filters( 'the_content', $post->post_content );
	$markdown    = aivb_html_to_markdown( $raw_content );

	// Extract FAQ items and append as structured Q&A.
	$faq_items    = aivb_extract_faq_items( $post->post_content );
	$faq_markdown = '';

	if ( ! empty( $faq_items ) ) {
		$faq_markdown .= "\n\n---\n\n## FAQs\n\n";
		foreach ( $faq_items as $item ) {
			$faq_markdown .= '**Q: ' . sanitize_text_field( $item['question'] ) . "**\n\n";
			$faq_markdown .= 'A: ' . sanitize_text_field( $item['answer'] ) . "\n\n";
		}
	}

	// Build the full Markdown document.
	$output  = '# ' . sanitize_text_field( $post->post_title ) . "\n\n";
	$output .= '**URL:** ' . esc_url_raw( $permalink ) . "  \n";
	$output .= '**Published:** ' . esc_html( $pub_date ) . "  \n";
	$output .= '**Modified:** ' . esc_html( get_the_modified_date( 'Y-m-d', $post_id ) ) . "  \n";

	if ( ! empty( $cat_list ) ) {
		$output .= '**Category:** ' . esc_html( $cat_list ) . "  \n";
	}

	$output .= "\n";

	if ( ! empty( $summary ) ) {
		$output .= "## Summary\n\n";
		$output .= esc_html( $summary ) . "\n\n";
		$output .= "---\n\n";
	}

	$output .= "## Content\n\n";
	$output .= $markdown;
	$output .= $faq_markdown;
	$output .= "\n\n---\n\n";
	$output .= '*Generated by [AI Visibility Booster](https://github.com/akshay-hmmbiz/ai-visibility-booster) — Plugin by Akshay Bhimani*' . "\n";

	// Send appropriate headers.
	nocache_headers();
	header( 'Content-Type: text/markdown; charset=UTF-8' );
	header( 'X-Content-Type-Options: nosniff' );
	header( 'X-Robots-Tag: noindex' );
	header( 'Access-Control-Allow-Origin: *' );
	header( 'Content-Disposition: inline; filename="' . sanitize_file_name( $slug ) . '.md"' );

	// phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
	echo $output;
	exit;
}

// ─── HTML to Markdown Converter ───────────────────────────────────────────────

/**
 * Convert an HTML string to Markdown format.
 *
 * Handles the most common HTML elements. Does not require external libraries.
 * Scripts, styles, and potentially harmful tags are removed before conversion.
 *
 * @param string $html Raw HTML content.
 * @return string Converted Markdown string.
 */
function aivb_html_to_markdown( $html ) {
	if ( empty( $html ) ) {
		return '';
	}

	// ── Strip dangerous elements ───────────────────────────────────────────────
	$html = preg_replace( '@<script[^>]*?>.*?</script>@si', '', $html );
	$html = preg_replace( '@<style[^>]*?>.*?</style>@si', '', $html );
	$html = preg_replace( '@<noscript[^>]*?>.*?</noscript>@si', '', $html );
	$html = preg_replace( '/<!--.*?-->/s', '', $html );

	// ── Code blocks (must be before inline code) ──────────────────────────────
	$html = preg_replace_callback(
		'@<pre[^>]*?>\s*<code[^>]*?>(.*?)</code>\s*</pre>@si',
		static function ( $m ) {
			$code = html_entity_decode( strip_tags( $m[1] ), ENT_QUOTES | ENT_HTML5, 'UTF-8' );
			return "\n\n```\n" . trim( $code ) . "\n```\n\n";
		},
		$html
	);

	// ── Headings ──────────────────────────────────────────────────────────────
	for ( $i = 6; $i >= 1; $i-- ) {
		$hashes = str_repeat( '#', $i );
		$html   = preg_replace(
			'@<h' . $i . '[^>]*?>(.*?)</h' . $i . '>@si',
			"\n\n$hashes $1\n\n",
			$html
		);
	}

	// ── Bold & Italic ─────────────────────────────────────────────────────────
	$html = preg_replace( '@<strong[^>]*?>(.*?)</strong>@si', '**$1**', $html );
	$html = preg_replace( '@<b\b[^>]*?>(.*?)</b>@si', '**$1**', $html );
	$html = preg_replace( '@<em\b[^>]*?>(.*?)</em>@si', '*$1*', $html );
	$html = preg_replace( '@<i\b[^>]*?>(.*?)</i>@si', '*$1*', $html );

	// ── Inline code ───────────────────────────────────────────────────────────
	$html = preg_replace( '@<code[^>]*?>(.*?)</code>@si', '`$1`', $html );

	// ── Links ─────────────────────────────────────────────────────────────────
	$html = preg_replace(
		'@<a\b[^>]+href=["\']([^"\']*)["\'][^>]*?>(.*?)</a>@si',
		'[$2]($1)',
		$html
	);

	// ── Images ────────────────────────────────────────────────────────────────
	$html = preg_replace(
		'@<img[^>]+src=["\']([^"\']*)["\'][^>]*?(?:alt=["\']([^"\']*)["\'])?[^>]*?/?>@si',
		'![$2]($1)',
		$html
	);

	// ── Blockquotes ───────────────────────────────────────────────────────────
	$html = preg_replace( '@<blockquote[^>]*?>(.*?)</blockquote>@si', "\n> $1\n", $html );

	// ── Horizontal rules ──────────────────────────────────────────────────────
	$html = preg_replace( '@<hr[^>]*?>@si', "\n\n---\n\n", $html );

	// ── Line breaks ───────────────────────────────────────────────────────────
	$html = preg_replace( '@<br[^>]*?>@si', "  \n", $html );

	// ── Unordered lists ───────────────────────────────────────────────────────
	$html = preg_replace_callback(
		'@<ul[^>]*?>(.*?)</ul>@si',
		static function ( $m ) {
			$items = preg_replace( '@<li\b[^>]*?>(.*?)</li>@si', "\n- $1", $m[1] );
			return "\n" . $items . "\n";
		},
		$html
	);

	// ── Ordered lists ─────────────────────────────────────────────────────────
	$counter = 0;
	$html    = preg_replace_callback(
		'@<ol[^>]*?>(.*?)</ol>@si',
		static function ( $m ) use ( &$counter ) {
			$counter = 0;
			$items   = preg_replace_callback(
				'@<li\b[^>]*?>(.*?)</li>@si',
				static function ( $li ) use ( &$counter ) {
					++$counter;
					return "\n$counter. " . $li[1];
				},
				$m[1]
			);
			return "\n" . $items . "\n";
		},
		$html
	);

	// ── Tables (basic) ────────────────────────────────────────────────────────
	// Convert tables to a simplified representation.
	$html = preg_replace( '@<th\b[^>]*?>(.*?)</th>@si', ' **$1** |', $html );
	$html = preg_replace( '@<td[^>]*?>(.*?)</td>@si', ' $1 |', $html );
	$html = preg_replace( '@<tr\b[^>]*?>(.*?)</tr>@si', "\n|$1\n", $html );
	$html = preg_replace( '@<t(?:head|body|foot)[^>]*?>(.*?)</t(?:head|body|foot)>@si', "$1", $html );
	$html = preg_replace( '@<table[^>]*?>(.*?)</table>@si', "\n$1\n", $html );

	// ── Paragraphs & divs ─────────────────────────────────────────────────────
	$html = preg_replace( '@<p\b[^>]*?>(.*?)</p>@si', "\n\n$1\n\n", $html );
	$html = preg_replace( '@<div[^>]*?>(.*?)</div>@si', "\n$1\n", $html );

	// ── Strip remaining tags ──────────────────────────────────────────────────
	$html = strip_tags( $html );

	// ── Decode HTML entities ──────────────────────────────────────────────────
	$html = html_entity_decode( $html, ENT_QUOTES | ENT_HTML5, 'UTF-8' );

	// ── Normalize whitespace ──────────────────────────────────────────────────
	$html = preg_replace( '/[ \t]+/', ' ', $html );
	$html = preg_replace( '/\n{3,}/', "\n\n", $html );
	$html = trim( $html );

	return $html;
}
